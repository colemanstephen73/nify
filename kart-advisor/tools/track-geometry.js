// Centreline → per-corner data, written to data/geometry/<track>.yaml (merged into the track by the build).
//
// Usage:
//   node tools/track-geometry.js <track-id> overpass <overpass.json> [--way <id>] [--config main]
//   node tools/track-geometry.js <track-id> pixels <trace.json> [--config main]
//
// overpass.json: the output of the Overpass query in README.md ("out geom;"). Pick the way with --way
//   when the file holds more than one raceway (the longest closed way is used by default).
// trace.json (screenshot trace): { "image": "tracks/ovrp/images/overhead.png", "points": [[x, y], ...],
//   "metresPerPixel": 0.21 } or { ..., "targetLengthFt": 3960 } to scale to the published lap length.
//   Points must follow the direction of travel. Everything traced from imagery is marked inferred.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';
import { analyzeCentreline, fromLatLon, fromPixels } from '../engine/geometry.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const [track, kind, file, ...rest] = process.argv.slice(2);
const opt = k => { const i = rest.indexOf(`--${k}`); return i >= 0 ? rest[i + 1] : null; };
if (!track || !['overpass', 'pixels'].includes(kind) || !file) {
  console.error('usage: node tools/track-geometry.js <track-id> overpass|pixels <file> [--way id] [--config main]');
  process.exit(2);
}
const input = JSON.parse(fs.readFileSync(file, 'utf8'));
const today = new Date().toISOString().slice(0, 10);
let pts, source, confidence, method;

if (kind === 'overpass') {
  const ways = (input.elements || []).filter(e => e.type === 'way' && e.geometry?.length > 3);
  const wanted = opt('way');
  const way = wanted ? ways.find(w => String(w.id) === wanted) : ways.sort((a, b) => b.geometry.length - a.geometry.length)[0];
  if (!way) throw new Error('no raceway way found in the Overpass file');
  pts = fromLatLon(way.geometry.map(g => [g.lat, g.lon]));
  source = { url: `https://www.openstreetmap.org/way/${way.id}`, title: `OpenStreetMap way ${way.id} (${way.tags?.name || 'raceway'})`, confidence: 'expert_consensus', accessed: today, notes: 'OSM contributors trace from aerial imagery; check the layout matches the current track.' };
  confidence = 'expert_consensus';
  method = `OSM way ${way.id}`;
} else {
  pts = fromPixels(input.points, { metresPerPixel: input.metresPerPixel, targetLengthM: input.targetLengthFt ? input.targetLengthFt * 0.3048 : input.targetLengthM });
  source = { kind: 'observation', title: `Centreline traced from ${input.image || 'a screenshot'}`, confidence: 'inferred', accessed: today, notes: input.metresPerPixel ? 'scaled with a scale bar' : `scaled to the published lap length (${input.targetLengthFt} ft)` };
  confidence = 'inferred';
  method = `traced from ${input.image || 'screenshot'}`;
}

const r = analyzeCentreline(pts);
for (const w of r.warnings) console.warn(`WARNING: ${w}`);
const doc = {
  schema_version: 1, updated: today, track, configuration: opt('config') || 'main',
  method: { value: method, sources: ['centreline'], confidence },
  sources: { centreline: source },
  length_m: { value: r.lengthM, sources: ['centreline'], confidence },
  corners: r.corners.map(c => ({ ...c, sources: ['centreline'], confidence: confidence === 'inferred' ? 'inferred' : confidence, ...(confidence === 'inferred' ? { derivation: 'curvature of the traced centreline' } : {}) })),
  demands: { ...r.demands, sources: ['centreline'], confidence: 'inferred', derivation: 'engine/geometry.js summarizeDemands' },
  warnings: r.warnings,
  outline_m: { value: r.outline, sources: ['centreline'], confidence, ...(confidence === 'inferred' ? { derivation: 'smoothed traced centreline, metres, x east / y north of the trace start' } : {}) },
};
fs.mkdirSync(path.join(root, 'data/geometry'), { recursive: true });
const out = path.join(root, 'data/geometry', `${track}.yaml`);
fs.writeFileSync(out, `# Generated by tools/track-geometry.js. Corners are ${confidence === 'inferred' ? 'INFERRED from imagery: confirm trackside' : 'from OpenStreetMap'}.\n` + yaml.dump(doc, { lineWidth: 140, flowLevel: 3 }));
console.table(r.corners.map(c => ({ n: c.number, dir: c.direction, type: c.type, angle: c.turnAngleDeg, R_m: c.minRadiusM, straight_before_m: c.precedingStraightM })));
console.log(r.demands);
console.log(`wrote ${path.relative(root, out)}`);
